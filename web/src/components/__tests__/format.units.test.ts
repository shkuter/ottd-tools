/**
 * Где называется единица измерения. Заголовок колонки называет её один раз, над
 * числами, которые её не несут; поле держит её при числе, рядом с вводимым
 * значением. Раньше эти два места смешивались: подпись «Длина станции (клеток)»
 * стояла над колонкой из «5 клеток».
 */
import { describe, expect, it } from 'vitest';
import { unitSuffix, withUnit } from '../format';

describe('единица измерения', () => {
  it('в заголовке колонки присоединяется запятой', () => {
    expect(withUnit('Round trip', 'days')).toBe('Round trip, days');
  });

  it('со слешем читается как «на» и запятой не требует', () => {
    // спека называет эту подпись как «Выпуск источника/мес.», а не «Выпуск, /мес.»
    expect(withUnit('Source output', '/month')).toBe('Source output/month');
  });

  it('в поле идёт следом за числом', () => {
    expect(unitSuffix('tiles')).toBe(' tiles');
  });

  it('отбивается одинаково, кем бы ни запрашивалась', () => {
    // пробел один и приходит из хелпера, а не из каждого места вызова
    expect(unitSuffix('кл.').startsWith(' ')).toBe(true);
    expect(unitSuffix('кл.').trim()).toBe('кл.');
  });
});
